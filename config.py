def term_explain(term, default=""):
    """取某术语的解释；没有则返回 default。"""
    try:
        return TERM_GLOSSARY.get(str(term or ""), default)
    except Exception:
        return default


def term_tip(term):
    """构造 ToolTip 文本：术语 + 解释；无解释返回空串（不弹窗）。"""
    desc = term_explain(term)
    if not desc:
        return ""
    return "%s\n——\n%s" % (term, desc)
